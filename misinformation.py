def explain_prediction(article_index, top_n=10):

    # TF-IDF features for one test article
    row = X_test_adaptive[article_index]

    # Contribution of each feature to the class difference
    contributions = (
        row.multiply(log_ratio).toarray().ravel()
    )

    # Only consider words present in the article
    present_indices = row.indices

    # Rank by absolute contribution
    ranked_indices = sorted(
        present_indices,
        key=lambda i: abs(contributions[i]),
        reverse=True
    )[:top_n]

    explanation = pd.DataFrame({
        "Word or phrase": feature_names[ranked_indices],
        "Contribution": contributions[ranked_indices]
    })

    explanation["Influence"] = np.where(
        explanation["Contribution"] > 0,
        "Misinformation",
        "Real"
    )

    return explanation


