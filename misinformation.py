# Load the saved model
saved = joblib.load("misinformation_detector.joblib")

app_tfidf = saved["vectorizer"]
app_model = saved["model"]
app_weights = saved["weights"]

app_features = app_tfidf.get_feature_names_out()

app_log_ratio = (
    app_model.feature_log_prob_[1]
    - app_model.feature_log_prob_[0]
)


def detect_misinformation(article):

    if not article or not article.strip():
        return (
            "Please enter a news article.",
            "",
            pd.DataFrame(columns=["Term", "Contribution", "Influence"])
        )

    # Transform the article using the training vocabulary
    article_vector = app_tfidf.transform([article])

    # Apply the same adaptive weights used during training
    article_vector = article_vector.multiply(
        app_weights
    ).tocsr()

    # Predict the probability of the misinformation class
    fake_probability = float(
        app_model.predict_proba(article_vector)[0, 1]
    )

    decision = verification_decision(fake_probability)

    # Build a readable prediction
    result = f"""
### Prediction: {decision}

**Estimated misinformation probability:** {fake_probability:.2%}

**Estimated real-class probability:** {(1 - fake_probability):.2%}

**Decision thresholds:** ≤20% likely reliable; ≥80% potential
misinformation; otherwise needs verification.
"""

    # Find the strongest word contributions
    contributions = (
        article_vector.multiply(app_log_ratio)
        .toarray()
        .ravel()
    )

    present_indices = article_vector.indices

    ranked = sorted(
        present_indices,
        key=lambda i: abs(contributions[i]),
        reverse=True
    )[:10]

    explanation = pd.DataFrame({
        "Term": app_features[ranked],
        "Contribution": np.round(contributions[ranked], 4)
    })

    explanation["Influence"] = np.where(
        explanation["Contribution"] > 0,
        "Misinformation",
        "Real"
    )

    explanation = explanation[
    ["Term", "Contribution", "Influence"]
].reset_index(drop=True)

    warning = (
        "Important: This is a machine-learning prediction based on "
        "patterns in the training dataset. It does not independently "
        "verify factual claims or establish that an article is true "
        "or false. Verify important claims using reliable sources."
    )

    return result, warning, explanation


